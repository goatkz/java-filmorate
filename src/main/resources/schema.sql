
CREATE TABLE IF NOT EXISTS mpa (
                                   id INTEGER PRIMARY KEY,
                                   name VARCHAR(20) NOT NULL UNIQUE
    );

CREATE TABLE IF NOT EXISTS genres (
                                      id INTEGER PRIMARY KEY,
                                      name VARCHAR(50) NOT NULL UNIQUE
    );

CREATE TABLE IF NOT EXISTS users (
                                     id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                     email VARCHAR(255) NOT NULL UNIQUE,
    login VARCHAR(100) NOT NULL UNIQUE,
    name VARCHAR(100) NOT NULL,
    birthday DATE
    );

CREATE TABLE IF NOT EXISTS films (
                                     id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                     name VARCHAR(255) NOT NULL,
    description VARCHAR(200),
    release_date DATE NOT NULL,
    duration INTEGER NOT NULL,
    mpa_id INTEGER NOT NULL,
    CONSTRAINT fk_films_mpa
    FOREIGN KEY (mpa_id) REFERENCES mpa(id)
    );

CREATE TABLE IF NOT EXISTS film_genres (
                                           film_id INTEGER NOT NULL,
                                           genre_id INTEGER NOT NULL,
                                           genre_order INTEGER NOT NULL DEFAULT 0,
                                           PRIMARY KEY (film_id, genre_id),
    FOREIGN KEY (film_id) REFERENCES films(id) ON DELETE CASCADE,
    FOREIGN KEY (genre_id) REFERENCES genres(id)
    );

ALTER TABLE film_genres
    ADD COLUMN IF NOT EXISTS genre_order INTEGER DEFAULT 0 NOT NULL;

CREATE TABLE IF NOT EXISTS film_likes (
                                          film_id INTEGER NOT NULL,
                                          user_id INTEGER NOT NULL,
                                          PRIMARY KEY (film_id, user_id),
    FOREIGN KEY (film_id) REFERENCES films(id) ON DELETE CASCADE,
    FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
    );

CREATE TABLE IF NOT EXISTS user_friends (
                                            user_id INTEGER NOT NULL,
                                            friend_id INTEGER NOT NULL,
                                            PRIMARY KEY (user_id, friend_id),
    FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
    FOREIGN KEY (friend_id) REFERENCES users(id) ON DELETE CASCADE,
    CHECK (user_id <> friend_id)
    );

CREATE INDEX IF NOT EXISTS idx_film_genres_genre
    ON film_genres(genre_id);

CREATE INDEX IF NOT EXISTS idx_film_likes_user
    ON film_likes(user_id);

CREATE INDEX IF NOT EXISTS idx_user_friends_friend
    ON user_friends(friend_id);
